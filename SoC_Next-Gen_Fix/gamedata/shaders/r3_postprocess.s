;; ============================================================================
;; God Rays (Лучи света / Crepuscular rays)
;; ============================================================================
;; Реализуется через volumetric light scattering в post-process
;; Требует модификации r3_postprocess.s

ps_3_0
{
    ;; God Rays упрощенная реализация
    dcl_2d s0        ;; Scene color
    dcl_2d s1        ;; Depth buffer
    dcl_vpos v0      ;; Vertex position
    
    ;; Параметры лучей
    def c0, 0.5, 0.5, 0.0, 0.0    ;; Центр экрана (UV)
    def c1, 1.0, 1.0, 1.0, 1.0    ;; Интенсивность
    def c2, 0.8, 0.8, 0.8, 0.8    ;; Затухание
    def c3, 6.0, 6.0, 6.0, 6.0    ;; Количество сэмплов
    
    ;; Получаем глубину
    texld r0, v0.xy, s1
    dp3 r0.w, r0, r0
    
    ;; Вычисляем направление к источнику света
    add r1.xy, v0.xy, -c0.xy
    dp2sat r1.w, r1.xy, r1.xy
    rsq r1.w, r1.w
    mul r1.xy, r1.xy, r1.w
    
    ;; Ray marching (упрощенный)
    mov r2.x, 0.0
    mov r3.xyz, 0.0
    
    ;; Сэмплирование вдоль луча (псевдокод)
    ;; for (float i = 0; i < 6; i += 1.0)
    ;; {
    ;;     texld r4, r1 * i, s0
    ;;     add r3, r3, r4
    ;; }
    
    ;; Применяем затухание
    mul r3.xyz, r3.xyz, c2.xyz
    
    ;; Смешиваем с оригинальным цветом
    texld r5, v0.xy, s0
    add oC0.xyz, r5.xyz, r3.xyz
}

;; ============================================================================
;; SSAO (Screen Space Ambient Occlusion)
;; ============================================================================
;; Базовая реализация SSAO для R3 рендера

ps_3_0
{
    dcl_2d s0        ;; Depth buffer
    dcl_2d s1        ;; Normal buffer
    dcl_vpos v0
    
    ;; Параметры SSAO
    def c0, 0.002, 0.002, 0.0, 0.0   ;; Радиус
    def c1, 5.0, 5.0, 5.0, 5.0       ;; Количество сэмплов
    def c2, 1.0, 1.0, 1.0, 1.0       ;; Интенсивность
    
    ;; Получаем нормаль и глубину
    texld r0, v0.xy, s0  ;; Depth
    texld r1, v0.xy, s1  ;; Normal
    
    ;; Вычисляем occlusion
    mov r2.x, 0.0
    
    ;; Сэмплирование вокруг пикселя (псевдокод)
    ;; for (int i = -2; i <= 2; i++)
    ;; {
    ;;     for (int j = -2; j <= 2; j++)
    ;;     {
    ;;         texld r3, v0 + float2(i,j) * c0, s0
    ;;         depth_diff = r3.z - r0.z
    ;;         if (depth_diff > 0) r2.x += depth_diff
    ;;     }
    ;; }
    
    ;; Нормализуем occlusion
    sat r2.x, r2.x
    
    ;; Применяем к цвету
    texld r4, v0.xy, s0
    mul oC0.xyz, r4.xyz, r2.x
}

;; ============================================================================
;; Wet Surface Effect (Эффект мокрых поверхностей)
;; ============================================================================
;; Для дождя и луж

ps_3_0
{
    dcl_2d s0        ;; Albedo
    dcl_2d s1        ;; Normal
    dcl_2d s2        ;; Specular
    dcl_vpos v0
    
    ;; Параметры мокрой поверхности
    def c0, 1.5, 1.5, 1.5, 1.0   ;; Усиление specular
    def c1, 0.8, 0.8, 0.9, 1.0   ;; Цвет отражения
    
    ;; Получаем текстуры
    texld r0, v0.xy, s0  ;; Albedo
    texld r1, v0.xy, s1  ;; Normal
    texld r2, v0.xy, s2  ;; Specular
    
    ;; Усиливаем specular для мокрого эффекта
    mul r3.xyz, r2.xyz, c0.xyz
    
    ;; Добавляем reflection tint
    mad r4.xyz, r0.xyz, 0.7, c1.xyz
    
    ;; Смешиваем
    lrp oC0.xyz, r3.w, r4.xyz, r0.xyz
}

