;; SoC Next-Gen Fix - Post-process шейдеры для God Rays и эффектов
;; Формат: .s файл для компиляции через fxc.exe из X-Ray SDK
;; Реализует: God Rays (объемные лучи), Wet Surface, Color Grading

;; ============================================================================
;; Директивы компилятора
;; ============================================================================
;; Требуется Shader Model 3.0 для полноценных эффектов

;; ============================================================================
;; Вершинный шейдер для полноэкранного квада (SM 3.0)
;; ============================================================================

vs_3_0
{
    dcl_position v0          ;; Позиция вершины (полноэкранный квад)
    dcl_texcoord v1          ;; UV координаты
    
    ;; Прямая передача позиции
    mov oPos.xy, v0.xy
    mov oPos.zw, v1.xy
    
    ;; Передача UV
    mov oT0.xy, v1.xy
}

;; ============================================================================
;; Пиксельный шейдер - God Rays (Volumetric Light Rays)
;; ============================================================================

ps_3_0
{
    ;; Декларация семплеров
    dcl_2d s0              ;; Scene color buffer
    dcl_2d s1              ;; Depth buffer
    dcl_2d s2              ;; Light occlusion map
    
    ;; Входные UV
    dcl t0.xy
    
    ;; Константы
    ;; cGodRayCenter - центр лучей (позиция солнца в экранном пространстве)
    ;; cGodRayDecay - затухание лучей
    ;; cGodRayWeight - вес каждого сэмпла
    ;; cGodRayExposure - экспозиция лучей
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 1: Сэмплинг сцены и глубины
    ;; ------------------------------------------------------------------------
    
    texld r0, t0, s0       ;; r0 = scene color
    texld r1, t0, s1       ;; r1 = depth
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 2: Вычисление направления к солнцу
    ;; ------------------------------------------------------------------------
    
    sub r2.xy, t0, cGodRayCenter     ;; vector to sun
    dp2_sat r2.w, r2, r2             ;; distance^2
    rsq r2.w, r2.w                   ;; distance
    nrm r2.xyz, r2                   ;; normalize direction
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 3: Ray marching вдоль направления к солнцу
    ;; ------------------------------------------------------------------------
    
    ;; Параметры ray marching
    mov r3.x, 64                     ;; количество сэмплов
    mov r3.y, cGodRayDecay           ;; decay
    mov r3.z, cGodRayWeight          ;; weight
    mov r3.w, cGodRayExposure        ;; exposure
    
    ;; Начальная позиция
    mul r4.xy, r2.xy, r3.x           ;; step size
    add r5.xy, t0, r4.xy             ;; start position
    
    ;; Инициализация суммы
    mov r6.xyz, 0                    ;; accumulation
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 4: Цикл ray marching (псевдокод, т.к. PS 3.0 не поддерживает циклы)
    ;; ------------------------------------------------------------------------
    
    ;; Примечание: В реальном шейдере цикл разворачивается вручную
    ;; Здесь показана концепция
    
    ;; Для каждого сэмпла:
    ;; 1. Сэмплируем глубину
    ;; 2. Проверяем occlusion
    ;; 3. Добавляем вклад в сумму с затуханием
    
    ;; Пример для первых нескольких сэмплов:
    texld r7, r5, s1                 ;; sample depth
    sub r8.x, r7.r, r1.r             ;; depth difference
    max r8.x, r8.x, 0                ;; clamp to positive
    mul r9.x, r8.x, r3.z             ;; apply weight
    mad r6.xyz, r9.x, r0, r6         ;; accumulate
    
    add r5.xy, r5.xy, r4.xy          ;; next sample
    
    ;; Повторить для всех 64 сэмплов...
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 5: Применение экспозиции и смешивание
    ;; ------------------------------------------------------------------------
    
    mul r6.xyz, r6.xyz, r3.w         ;; apply exposure
    mad oC0.xyz, r6, 0.5, r0         ;; blend with original
    
    mov oC0.w, r0.w                  ;; alpha
}

;; ============================================================================
;; Пиксельный шейдер - Wet Surface Effect (мокрые поверхности)
;; ============================================================================

ps_3_0_wet
{
    ;; Декларация семплеров
    dcl_2d s0              ;; Scene color
    dcl_2d s1              ;; Normal map
    dcl_2d s2              ;; Reflection map
    
    dcl t0.xy
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 1: Сэмплинг текстур
    ;; ------------------------------------------------------------------------
    
    texld r0, t0, s0       ;; scene color
    texld r1, t0, s1       ;; normals
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 2: Вычисление отражения
    ;; ------------------------------------------------------------------------
    
    ;; Нормализуем нормали
    mad r2.xyz, r1, 2.0, -1.0   ;; normalize from [0,1] to [-1,1]
    nrm r2.xyz, r2
    
    ;; Вычисляем вектор отражения
    ;; reflectVec = reflect(viewDir, normal)
    mov r3.xyz, cViewDirection
    neg r4.xyz, r3
    dp3 r5.x, r4, r2
    mul r5.xyz, r5.x, r2
    add r5.xyz, r5, r4
    nrm r5.xyz, r5
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 3: Сэмплинг карты отражений
    ;; ------------------------------------------------------------------------
    
    texld r6, r5, s2       ;; reflection color
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 4: Смешивание отражения с базовым цветом
    ;; ------------------------------------------------------------------------
    
    ;; Определяем силу отражения на основе roughness
    mov r7.x, 0.3          ;; base wetness
    
    ;; Увеличиваем отражение для темных участков (эффект мокрого асфальта)
    dp3 r8.x, r0, r0       ;; luminance
    rsq r8.x, r8.x
    mul r8.x, r8.x, 0.5
    add r7.x, r7.x, r8.x
    
    ;; Смешиваем
    lrp oC0.xyz, r7.x, r6, r0
    
    mov oC0.w, r0.w
}

;; ============================================================================
;; Пиксельный шейдер - Color Grading и Tone Mapping
;; ============================================================================

ps_3_0_colorgrade
{
    dcl_2d s0              ;; Input scene color
    dcl t0.xy
    
    texld r0, t0, s0       ;; input color
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 1: Tone Mapping (ACES Filmic)
    ;; ------------------------------------------------------------------------
    
    ;; ACES tone mapping curve
    mov r1.xyz, r0
    mul r2.xyz, r1, r1
    
    ;; a = x * (2.51x + 0.03)
    mul r3.xyz, r1, 2.51
    add r3.xyz, r3, 0.03
    mul r3.xyz, r1, r3
    
    ;; b = x * (2.43x + 0.59) + 0.14
    mul r4.xyz, r1, 2.43
    add r4.xyz, r4, 0.59
    mul r4.xyz, r1, r4
    add r4.xyz, r4, 0.14
    
    ;; result = a / b
    div r1.xyz, r3, r4
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 2: Color Correction
    ;; ------------------------------------------------------------------------
    
    ;; Применяем LUT или ручную коррекцию цвета
    ;; cColorCorrection - константы коррекции (gain, gamma, offset)
    
    ;; Gamma correction
    pow r2.xyz, r1, cGamma
    
    ;; Gain (яркость)
    mul r2.xyz, r2, cGain
    
    ;; Offset (смещение)
    add r2.xyz, r2, cOffset
    
    ;; ------------------------------------------------------------------------
    ;; Шаг 3: Saturation adjustment
    ;; ------------------------------------------------------------------------
    
    ;; Вычисляем luminance
    dp3 r3.x, r2, cLuminanceCoeff    ;; 0.2126*R + 0.7152*G + 0.0722*B
    
    ;; Интерполяция между grayscale и color
    mov r4.xyz, r3.x                 ;; grayscale
    lrp oC0.xyz, cSaturation, r2, r4 ;; mix based on saturation
    
    mov oC0.w, r0.w
}

;; ============================================================================
;; Техники
