technique T_GOD_RAYS
{
    pass P0
    {
        VertexShader = vs_3_0
        PixelShader = ps_3_0
        
        AlphaBlendEnable = true
        SrcBlend = SRC_ALPHA
        DestBlend = INV_SRC_ALPHA
        ZEnable = false
    }
}

technique T_WET_SURFACE
{
    pass P0
    {
        VertexShader = vs_3_0
        PixelShader = ps_3_0_wet
        
        AlphaBlendEnable = false
        ZEnable = false
    }
}

technique T_COLOR_GRADING
{
    pass P0
    {
        VertexShader = vs_3_0
        PixelShader = ps_3_0_colorgrade
        
        AlphaBlendEnable = false
        ZEnable = false
    }
}

;; ============================================================================
;; Примечания:
;; ============================================================================
;; 
;; Эти пост-процесс эффекты требуют:
;; 1. Рендеринга сцены в текстуру (off-screen buffer)
;; 2. Доступа к depth buffer
;; 3. Правильной настройки констант от движка
;; 
;; God Rays наиболее эффективны при:
;; - Использовании downscaled буфера (1/2 или 1/4 разрешения)
;; - Применении blur для сглаживания ступенчатости
;; - Настройке параметров под время суток
;; 
;; Wet Surface эффект работает лучше всего:
;; - Во время дождя или после него
;; - На поверхностях с low roughness (асфальт, металл)
;; - При наличии environment map для отражений
;; 
;; Color Grading должен быть последним эффектом в цепочке
;; перед выводом на экран.
;; 
;; ============================================================================
